def get_nested_value(data, path):
    """Get a nested value from dict using dot notation path"""
    keys = path.split('.')
    value = data
    for key in keys:
        if isinstance(value, dict) and key in value:
            value = value[key]
        else:
            return None
    return value

def set_nested_value(data, path, value):
    """Set a nested value in dict using dot notation path"""
    keys = path.split('.')
    current = data
    for key in keys[:-1]:
        if key not in current:
            current[key] = {}
        current = current[key]
    current[keys[-1]] = value

def apply_translations(data, lang_code):
    """Apply translations to a copy of the data"""
    import copy
    result = copy.deepcopy(data)

    if lang_code in TRANSLATIONS:
        for key_path, translation in TRANSLATIONS[lang_code].items():
            set_nested_value(result, key_path, translation)

    return result

